/**
 * Detects the district from any location text.
 * Supports: Bengali, Banglish, and English location names.
 * Searches from most specific (village) to least specific (district).
 */
export function detectDistrictFromText(text: string): string | null {
  if (!text || text.trim().length < 2) return null;

  const lower = text.toLowerCase().trim();

  // 1. Try English/Banglish alias lookup (longest match first to avoid partial hits)
  const sortedAliases = Object.keys(BANGLISH_LOCATION_ALIASES).sort((a, b) => b.length - a.length);
  for (const alias of sortedAliases) {
    if (lower.includes(alias)) {
      const bengali = BANGLISH_LOCATION_ALIASES[alias];
      const district = LOCATION_TO_DISTRICT[bengali];
      if (district) return district;
    }
  }

  // 2. Try Bengali direct lookup (longest match first)
  const sortedLocations = Object.keys(LOCATION_TO_DISTRICT).sort((a, b) => b.length - a.length);
  for (const loc of sortedLocations) {
    if (text.includes(loc)) {
      return LOCATION_TO_DISTRICT[loc];
    }
  }

  return null;
}

/**
 * Returns a random neighboring district for the given district.
 * Used by the geo social proof engine.
 */
export function getRandomNeighborDistrict(district: string): string | null {
  const neighbors = DISTRICT_NEIGHBORS[district];
  if (!neighbors || neighbors.length === 0) return null;
  return neighbors[Math.floor(Math.random() * neighbors.length)];
}
